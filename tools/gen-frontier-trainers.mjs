// Generates engine/frontier-trainers.js from the decomp: every Frontier
// trainer's class, name and monSet (as frontier mon ids, which are
// FRONTIER_POOL `index` values), and the trainer id ranges
// GetRandomScaledFrontierTrainerId draws from.
//   node tools/gen-frontier-trainers.mjs [path/to/pokeemerald]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = process.argv[2] ?? path.join(here, "../../pokeemerald");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");

// FRONTIER_MON_* -> id
const monIds = {};
for (const m of read("include/constants/battle_frontier_mons.h").matchAll(/#define\s+(FRONTIER_MON_\w+)\s+(\d+)/g)) monIds[m[1]] = Number(m[2]);
// FRONTIER_TRAINER_* -> id
const trainerIds = {};
for (const m of read("include/constants/battle_frontier_trainers.h").matchAll(/#define\s+(FRONTIER_TRAINER_\w+)\s+(\d+)/g)) trainerIds[m[1]] = Number(m[2]);

// The monSet file: multi-line #define lists, then arrays of macros / mon names.
const src = read("src/data/battle_frontier/battle_frontier_trainer_mons.h").replace(/\/\/.*$/gm, "").replace(/\\\r?\n/g, " ");
// Object-like (#define NAME body) and function-like (#define NAME(a, b) body,
// with FRONTIER_MON_##a pasting) macros, expanded textually until none is left.
const macros = {};
for (const m of src.matchAll(/#define\s+(FRONTIER_MONS_\w+)(\(([^)]*)\))?[ \t]+([^\n]*)/g)) {
  macros[m[1]] = { params: m[2] ? m[3].split(",").map((x) => x.trim()) : null, body: m[4] };
}
function substitute(text) {
  for (let pass = 0; pass < 20; pass++) {
    let changed = false;
    text = text.replace(/\b(FRONTIER_MONS_\w+)\b(\s*\(([^)]*)\))?/g, (all, name, call, args) => {
      const mac = macros[name];
      if (!mac) throw new Error(`unknown macro ${name}`);
      changed = true;
      if (!mac.params) {
        if (call) throw new Error(`${name} takes no arguments`);
        return mac.body;
      }
      const vals = args.split(",").map((x) => x.trim());
      if (vals.length !== mac.params.length) throw new Error(`${name}: ${vals.length} args for ${mac.params.length}`);
      let body = mac.body;
      mac.params.forEach((pn, i) => { body = body.replace(new RegExp(`\\b${pn}\\b`, "g"), vals[i]); });
      return body.replace(/\s*##\s*/g, "");
    });
    if (!changed) return text;
  }
  throw new Error("macro expansion did not settle");
}
const expand = (body) => substitute(body).split(",").map((t) => t.trim()).filter(Boolean).map((t) => {
  if (t === "-1" || t === "0xFFFF") return "END";
  if (!(t in monIds)) throw new Error(`unknown monSet token "${t}"`);
  return monIds[t];
});
const sets = {};
for (const m of src.matchAll(/const u16 (gBattleFrontierTrainerMons_\w+)\[\]\s*=\s*\{([^}]*)\}/g)) {
  const list = expand(m[2]);
  const end = list.indexOf("END");
  if (end !== list.length - 1) throw new Error(`${m[1]}: terminator at ${end} of ${list.length}`);
  sets[m[1]] = list.slice(0, end);
}

const trainers = [];
const tsrc = read("src/data/battle_frontier/battle_frontier_trainers.h");
for (const m of tsrc.matchAll(/\[(FRONTIER_TRAINER_\w+)\]\s*=\s*\{([\s\S]*?)\n    \}/g)) {
  const id = trainerIds[m[1]];
  const cls = m[2].match(/\.facilityClass\s*=\s*FACILITY_CLASS_(\w+)/)[1];
  const name = m[2].match(/\.trainerName\s*=\s*_\("([^"]*)"\)/)[1];
  const set = m[2].match(/\.monSet\s*=\s*(\w+)/)[1];
  if (!sets[set]) throw new Error(`${m[1]}: no monSet ${set}`);
  trainers[id] = { id, cls, name, monSet: sets[set] };
}
if (trainers.length !== 300 || trainers.some((t) => !t)) throw new Error(`expected 300 trainers, got ${trainers.filter(Boolean).length}`);

// sFrontierTrainerIdRanges / ...Hard (src/battle_tower.c)
const tower = read("src/battle_tower.c");
const ranges = (name) => [...tower.match(new RegExp(`${name}\\[\\]\\[2\\]\\s*=\\s*\\{([\\s\\S]*?)\\};`))[1]
  .matchAll(/\{(FRONTIER_TRAINER_\w+),\s*(FRONTIER_TRAINER_\w+)\}/g)].map((r) => [trainerIds[r[1]], trainerIds[r[2]]]);
const normal = ranges("sFrontierTrainerIdRanges"), hard = ranges("sFrontierTrainerIdRangesHard");
if (normal.length !== 8 || hard.length !== 8) throw new Error("range tables");

const out = `// ── frontier-trainers.js ───────────────────────────────────────────────────
// GENERATED by tools/gen-frontier-trainers.mjs from pokeemerald -- do not hand-edit.
//   gBattleFrontierTrainers (src/data/battle_frontier/battle_frontier_trainers.h)
//   monSets (src/data/battle_frontier/battle_frontier_trainer_mons.h), as
//     frontier mon ids (= FRONTIER_POOL index), in table order, duplicates kept
//   sFrontierTrainerIdRanges / sFrontierTrainerIdRangesHard (src/battle_tower.c)

export const FRONTIER_TRAINERS = [
${trainers.map((t) => `  ${JSON.stringify(t)},`).join("\n")}
];

export const TRAINER_ID_RANGES = ${JSON.stringify(normal)};
export const TRAINER_ID_RANGES_HARD = ${JSON.stringify(hard)};
`;
fs.writeFileSync(path.join(here, "../engine/frontier-trainers.js"), out);
console.log(`wrote ${trainers.length} trainers; monSet sizes ${Math.min(...trainers.map((t) => t.monSet.length))}-${Math.max(...trainers.map((t) => t.monSet.length))}; ranges ${JSON.stringify(normal)} / ${JSON.stringify(hard)}`);
